export const HERO_ALT_KEYS = {
  male: "imageAltMale",
  female: "imageAltFemale",
} as const;
export type Gender = keyof typeof HERO_ALT_KEYS;

// "colorNavy" -> "navy", "colorSkyBlue" -> "skyBlue" — turns a color's
// translation key into the slug used in its image filename below.
export function colorSlug(nameKey: string): string {
  const rest = nameKey.slice("color".length);
  return rest.charAt(0).toLowerCase() + rest.slice(1);
}

// One photo per gender × model × color combination — 192 placeholder
// PNGs in public/images/products/ (all currently the same Pexels photo),
// generated by a one-off script, not checked-in source photography. Real
// per-combination product photos replace these one file at a time later:
// same filename, real content — no code change needed when that happens.
export function productImagePath(
  gender: Gender,
  model: ModelKey,
  colorNameKey: string,
): string {
  return `/images/products/${gender}-${model}-${colorSlug(colorNameKey)}.png`;
}

