export type CityKey = "LA_PAZ" | "SANTA_CRUZ";
export const CITY_KEYS: CityKey[] = ["LA_PAZ", "SANTA_CRUZ"];

export function isModelKey(value: string): value is ModelKey {
  return MODELS.some((model) => model.key === value);
}

export function isSize(value: string): value is Size {
  return (SIZES as readonly string[]).includes(value);
}

export function isCityKey(value: string): value is CityKey {
  return CITY_KEYS.includes(value as CityKey);
}

export function isColorForGender(gender: Gender, nameKey: string): boolean {
  return PALETTE[gender].some((color) => color.nameKey === nameKey);
}

// Picks a random valid {gender, model, color} triple — used by the
// pedido/cotización page's RandomImageCycler when the visitor arrives
// with no selection at all.
export function randomCatalogCombo(): {
  gender: Gender;
  model: ModelKey;
  colorNameKey: string;
} {
  const genders: Gender[] = ["male", "female"];
  const gender = genders[Math.floor(Math.random() * genders.length)];
  const model = MODELS[Math.floor(Math.random() * MODELS.length)].key;
  const palette = PALETTE[gender];
  const colorNameKey = palette[Math.floor(Math.random() * palette.length)].nameKey;
  return { gender, model, colorNameKey };
}
